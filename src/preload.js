const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('kat', {
  onCursor: (cb) => ipcRenderer.on('cursor', (_e, data) => cb(data)),
  moveWindow: (x, y, snapBottom = false) => ipcRenderer.send('move-window', { x, y, snapBottom }),
  getWorkArea: () => ipcRenderer.invoke('get-work-area'),
  showContextMenu: () => ipcRenderer.send('show-context-menu'),
  setIgnoreMouse: (ignore) => ipcRenderer.send('set-ignore-mouse', ignore),
  onAgentEvent: (cb) => ipcRenderer.on('agent-event', (_e, payload) => cb(payload)),
  onAgentProcs: (cb) => ipcRenderer.on('agent-procs', (_e, cpu) => cb(cpu)),
  onUserTyping: (cb) => ipcRenderer.on('user-typing', (_e, ts) => cb(ts)),
  reportAnim: (anim) => ipcRenderer.send('anim-report', anim),
  focusWindow: () => ipcRenderer.send('focus-window'),
  sendChat: (text, seq) => ipcRenderer.send('chat-send', { text, seq }),
  resetChat: () => ipcRenderer.send('chat-reset'),
  onChatThinking: (cb) => ipcRenderer.on('chat-thinking', () => cb()),
  onChatDelta: (cb) => ipcRenderer.on('chat-delta', (_e, payload) => cb(payload)),
  onChatReply: (cb) => ipcRenderer.on('chat-reply', (_e, payload) => cb(payload)),
  onChatError: (cb) => ipcRenderer.on('chat-error', (_e, payload) => cb(payload)),
  onSkillThinking: (cb) => ipcRenderer.on('skill-thinking', () => cb()),
  onSkillReply: (cb) => ipcRenderer.on('skill-reply', (_e, text) => cb(text)),
  onSkillError: (cb) => ipcRenderer.on('skill-error', (_e, msg) => cb(msg)),
  onSkillActive: (cb) => ipcRenderer.on('skill-active', (_e, payload) => cb(payload)),
  onSoundConfig: (cb) => ipcRenderer.on('sound-config', (_e, cfg) => cb(cfg)),
  onLangConfig: (cb) => ipcRenderer.on('lang-config', (_e, lang) => cb(lang)),
  onSkinConfig: (cb) => ipcRenderer.on('skin-config', (_e, base) => cb(base)),
  onPeerEvent: (cb) => ipcRenderer.on('peer-event', (_e, ev) => cb(ev)),
  onCatConfig: (cb) => ipcRenderer.on('cat-config', (_e, cfg) => cb(cfg)),
  neighborWave: (id) => ipcRenderer.send('neighbor-wave', id),
  slashCommands: () => ipcRenderer.invoke('slash-commands'),
  runSlash: (c) => ipcRenderer.invoke('chat-slash', c),
});
