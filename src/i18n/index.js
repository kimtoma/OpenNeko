const SUPPORTED = ['ko', 'en', 'ja', 'zh'];
const FALLBACK = 'en';

function normalizeLang(locale) {
  if (!locale) return null;
  const l = String(locale).toLowerCase();
  if (l.startsWith('ko')) return 'ko';
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('en')) return 'en';
  return null;
}
function resolveLang(savedLang, osLocale) {
  if (savedLang && SUPPORTED.includes(savedLang)) return savedLang;
  return normalizeLang(osLocale) || FALLBACK;
}
function get(obj, key) { return key.split('.').reduce((o, k) => (o == null ? o : o[k]), obj); }
function interp(s, vars) {
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? vars[k] : `{${k}}`));
}
function createI18n(lang) {
  const L = SUPPORTED.includes(lang) ? lang : FALLBACK;
  function t(key, vars) {
    let v = get(STRINGS[L], key);
    if (v == null) v = get(STRINGS[FALLBACK], key);
    if (v == null) return key;
    if (typeof v === 'function') return v(vars || {});
    return vars ? interp(v, vars) : v;
  }
  return { lang: L, t };
}
module.exports = { STRINGS, SUPPORTED, FALLBACK, normalizeLang, resolveLang, createI18n };
