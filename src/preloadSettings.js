const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('settings', {
  get: () => ipcRenderer.invoke('settings-get'),
  save: (payload) => ipcRenderer.invoke('settings-save', payload),
  test: (payload) => ipcRenderer.invoke('settings-test', payload),
  presets: () => ipcRenderer.invoke('settings-presets'),
  detect: () => ipcRenderer.invoke('settings-detect'),
  setSound: (cfg) => ipcRenderer.invoke('sound-set', cfg),
  setLang: (cfg) => ipcRenderer.invoke('lang-set', cfg),
  skinsList: () => ipcRenderer.invoke('skins-list'),
  setSkin: (cfg) => ipcRenderer.invoke('skin-set', cfg),
  setCatName: (cfg) => ipcRenderer.invoke('cat-name-set', cfg),
  setNeighbor: (cfg) => ipcRenderer.invoke('neighbor-set', cfg),
  resize: (height) => ipcRenderer.send('settings-resize', height),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  onboardPick: (cfg) => ipcRenderer.invoke('onboard-pick', cfg),
  onboardComplete: () => ipcRenderer.invoke('onboard-complete'),
  permStatus: () => ipcRenderer.invoke('onboard-perm-status'),
  openPerms: (cfg) => ipcRenderer.invoke('onboard-open-perms', cfg),
  skillsList: () => ipcRenderer.invoke('skills-list'),
  setSkillEnabled: (cfg) => ipcRenderer.invoke('skill-enabled', cfg),
  openSkillsFolder: () => ipcRenderer.invoke('open-skills-folder'),
  setWebSearch: (cfg) => ipcRenderer.invoke('websearch-set', cfg),
  setProfile: (p) => ipcRenderer.invoke('profile-set', p),
});
